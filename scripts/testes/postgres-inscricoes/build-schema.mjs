import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
import {directory,sql} from './docker-lab.mjs'
const catalog=JSON.parse(fs.readFileSync('relatorios-testes/banco-publicado.json','utf8'))
const quote=value=>'"'+value.replaceAll('"','""')+'"'
const base=catalog.tables.filter(table=>table.table_type==='BASE TABLE').map(table=>table.table_name)
const arrays={'campeonato_configuracoes.pontos_colocacao':'integer[]','campeonato_configuracoes.paypal_moedas':'text[]','campeonato_configuracoes.xtreino_mapas':'text[]','campeonato_jogos.mapas':'text[]','campeonato_jogos.grupos_ids':'uuid[]','campeonato_rulebooks.modules_ativos':'text[]'}
let ddl=`-- Isolated catalog reconstruction, no production connection or user data.
-- Catalog omits numeric precision, generated flags, owners/ACL and view definitions.
-- auth is a fixture; UPDATE column masks are taken from local SQL where matched.
create schema auth;
create schema extensions;
create extension pgcrypto with schema extensions;
create extension pg_trgm with schema extensions;
set search_path=public,extensions;
create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;
create role supabase_admin nologin bypassrls;
create role authenticator nologin;
create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb, raw_app_meta_data jsonb, created_at timestamptz default now(),updated_at timestamptz default now());
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
create function auth.role() returns text language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claim.role',true),''),current_setting('role',true))$$;
create sequence public.dropzone_public_id_seq;
`
for(const table of base){
  const columns=catalog.columns.filter(column=>column.table_name===table).sort((a,b)=>a.ordinal_position-b.ordinal_position)
  ddl+=`create table public.${quote(table)} (\n`+columns.map(column=>{
    const identity=(table==='equipe_lines'&&column.column_name==='public_id')||(table==='sistema_auditoria'&&column.column_name==='id')
    const type=column.data_type==='ARRAY'?arrays[table+'.'+column.column_name]:column.data_type
    assert.ok(type && type!=='USER-DEFINED')
    return `  ${quote(column.column_name)} ${type}${identity?(table==='sistema_auditoria'?' generated always as identity':' generated by default as identity'):''}${column.column_default&&!identity?' default '+column.column_default:''}${column.is_nullable==='NO'?' not null':''}`
  }).join(',\n')+'\n);\n'
}
for(const constraint of [...catalog.constraints.filter(item=>item.constraint_type!=='f'),...catalog.constraints.filter(item=>item.constraint_type==='f')]){
  if(base.includes(constraint.table_name))ddl+=`alter table public.${quote(constraint.table_name)} add constraint ${quote(constraint.constraint_name)} ${constraint.definition};\n`
}
const constraintNames=new Set(catalog.constraints.filter(item=>['p','u'].includes(item.constraint_type)).map(item=>item.constraint_name))
for(const index of catalog.indexes)if(base.includes(index.table_name)&&!constraintNames.has(index.index_name))ddl+=index.definition+';\n'
ddl+='set check_function_bodies=off;\n'
for(const fn of catalog.functions)ddl+=fn.definition+';\n'
ddl+='set check_function_bodies=on;\n'
const walk=folder=>fs.readdirSync(folder,{withFileTypes:true}).flatMap(entry=>entry.isDirectory()?walk(path.join(folder,entry.name)):entry.name.endsWith('.sql')?[path.join(folder,entry.name)]:[])
const localSql=walk('database/migrations').concat(walk('supabase/migrations')).sort().map(file=>({file,source:fs.readFileSync(file,'utf8')}))
const triggerGroups=new Map()
for(const trigger of catalog.triggers){const key=trigger.table_name+'.'+trigger.trigger_name;const item=triggerGroups.get(key)||{...trigger,events:[]};item.events.push(trigger.event_manipulation);triggerGroups.set(key,item)}
const reconstructed=[]
for(const trigger of triggerGroups.values()){
  if(!base.includes(trigger.table_name))continue
  const fn=trigger.action_statement.match(/FUNCTION\s+(?:public\.)?([\w]+)\s*\(/i)?.[1]
  let match=null
  for(const file of localSql){
    const expression=new RegExp('create\\s+trigger\\s+'+trigger.trigger_name+'\\b[^;]*?\\bon\\s+(?:public\\.)?'+trigger.table_name+'\\b[^;]*;', 'ig')
    for(const result of file.source.matchAll(expression)){
      if(new RegExp('function\\s+(?:public\\.)?'+fn+'\\s*\\(','i').test(result[0]))match={ddl:result[0],file:file.file}
    }
  }
  // Fallback reproduces catalog timing/events; UPDATE masks are missing from this export.
  const statement=match?.ddl||`create trigger ${quote(trigger.trigger_name)} ${trigger.action_timing} ${[...new Set(trigger.events)].join(' or ')} on public.${quote(trigger.table_name)} for each row ${trigger.action_statement};`
  ddl+=statement+'\n'
  reconstructed.push({table:trigger.table_name,name:trigger.trigger_name,source:match?.file||'catalog events only'})
}
for(const row of catalog.rls){if(base.includes(row.table_name)&&row.rls_enabled){ddl+=`alter table public.${quote(row.table_name)} enable row level security;\n`;if(row.rls_forced)ddl+=`alter table public.${quote(row.table_name)} force row level security;\n`}}
for(const policy of catalog.policies){
  if(!base.includes(policy.tablename))continue
  ddl+=`create policy ${quote(policy.policyname)} on public.${quote(policy.tablename)} for ${policy.cmd} to ${policy.roles.map(role=>role==='public'?'public':quote(role)).join(',')}${policy.qual?' using ('+policy.qual+')':''}${policy.with_check?' with check ('+policy.with_check+')':''};\n`
}
ddl+=`grant usage on schema public,auth,extensions to anon,authenticated,service_role;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;
revoke all on all functions in schema public from public,anon,authenticated;
grant execute on all functions in schema public to service_role;
`
fs.writeFileSync(directory+'/schema-reconstruction.sql',ddl)
fs.writeFileSync(directory+'/reconstructed-triggers.json',JSON.stringify(reconstructed,null,2))
if(process.argv.includes('--emit-only')){console.log('Reconstruction emitted; recovered equipe_lines.public_id and sistema_auditoria.id identities from local migrations.');process.exit(0)}
const out=await sql(ddl,{timeout:60000})
const result=JSON.parse(await sql(`select json_build_object('serverVersion',current_setting('server_version'),'baseTables',(select count(*) from information_schema.tables where table_schema='public' and table_type='BASE TABLE'),'constraints',(select count(*) from pg_constraint c join pg_class t on t.oid=c.conrelid join pg_namespace n on n.oid=t.relnamespace where n.nspname='public'),'functions',(select count(*) from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public'),'triggers',(select count(*) from pg_trigger g join pg_class t on t.oid=g.tgrelid join pg_namespace n on n.oid=t.relnamespace where n.nspname='public' and not g.tgisinternal));`))
Object.assign(result,{catalogGeneratedAt:catalog.generated_at,triggerMasksFromLocalSql:reconstructed.filter(item=>item.source!=='catalog events only').length,scope:'All exported public base tables/constraints/indexes/functions/policies; local trigger masks and fixture auth. Not a full fresh production clone: view definitions, precision/generated attributes, owner/ACL and Supabase infrastructure absent.'})
fs.writeFileSync(directory+'/schema-reconstruction-result.json',JSON.stringify(result,null,2))
console.log(JSON.stringify(result))
